-- =============================================================================
-- 0008_delete_non_oct3_entries.sql — 2026-10-03(KST) 외 날짜에 등록된 전도
-- 대상자 레코드를 영구 삭제(hard DELETE)한다.
-- =============================================================================
--
-- anon/authenticated role에는 DELETE 권한 자체가 부여돼 있지 않으므로
-- (0001_init.sql), 테이블 소유자(postgres) 권한으로 Supabase Dashboard →
-- SQL Editor에서 직접 실행해야 한다(이 저장소 규칙대로 에이전트가 직접
-- 실행하지 않고 파일로만 작성한다).
--
-- 대상(2026-10-03 확인 시점 기준, submitted_at을 Asia/Seoul로 환산한 날짜가
-- 2026-10-03이 아닌 행):
--   id 125 서연   2026-09-25 (KST)
--   id 126 병소정 2026-09-24 (KST)
--   id 127 예은   2026-09-23 (KST)
--   id 128 할머니 2026-09-22 (KST)
--   id 129 태윤   2026-09-21 (KST)
--   id 130 홍길동 2026-10-01 (KST, 이미 소프트 삭제된 행)
--
-- id 목록과 날짜 조건을 함께 걸어, 이 마이그레이션 작성 이후 새로 들어온
-- 10/3 데이터를 실수로 지우지 않도록 이중 안전장치를 둔다.
-- 소프트 삭제가 아닌 완전 삭제이므로 되돌릴 수 없다 — 실행 전 대상 id를
-- 반드시 재확인할 것.
-- =============================================================================

delete from public.holywin_entries
where id in (125, 126, 127, 128, 129, 130)
  and (submitted_at at time zone 'Asia/Seoul')::date <> '2026-10-03';
